import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "node_modules", "pdfjs-dist", "wasm");
const output = path.join(root, "packages", "reader", "src", "pdf-wasm-data.js");
// The decoders pdf.js 6 instantiates through the BinaryDataFactory
// (jbig2/ccitt, openjpeg, qcms, quickjs); the *_nowasm_fallback.js files are
// only used when wasm is disabled and cannot ship through a dynamic import.
const wanted = ["jbig2.wasm", "openjpeg.wasm", "qcms_bg.wasm", "quickjs-eval.wasm"];

const entries = wanted.map((name) => {
  const file = path.join(sourceDir, name);
  if (!fs.existsSync(file)) throw new Error(`pdf.js wasm module not found: ${name}; run npm install first`);
  const encoded = fs.readFileSync(file).toString("base64");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(encoded)},`;
});
const generated = [
  "// Generated by scripts/generate-pdf-wasm.mjs from pdfjs-dist. Do not edit by hand.",
  "export const EMBEDDED_PDF_WASM = Object.freeze({",
  ...entries,
  "});",
  "",
].join("\n");

fs.writeFileSync(output, generated);
console.log(`embedded ${wanted.length} pdf.js wasm modules`);
