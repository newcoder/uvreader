#!/usr/bin/env node
// Regenerate the bundled prompt modules from the human-edited prompt documents.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const prompts = [
  {
    document: "quiz-llm-prompt.txt",
    target: "quiz-llm-prompt.js",
    variable: "QUIZ_LLM_PROMPT",
  },
  {
    document: "quiz-llm-plain-prompt.txt",
    target: "quiz-llm-prompt-plain.js",
    variable: "QUIZ_LLM_PLAIN_PROMPT",
  },
];
for (const prompt of prompts) {
  const source = fs.readFileSync(path.join(root, "docs", prompt.document), "utf8");
  const target = path.join(root, "packages", "reader", "src", prompt.target);
  const output = `// Generated from docs/${prompt.document} by scripts/generate-quiz-llm-prompt.mjs.\n// Do not edit this file directly; edit the prompt document and regenerate.\nexport const ${prompt.variable} = ${JSON.stringify(source)};\n`;
  fs.writeFileSync(target, output, "utf8");
  console.log(target);
}
