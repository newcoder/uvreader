#!/usr/bin/env node
// Regenerate the bundled prompt module from the human-edited prompt document.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "docs", "quiz-llm-prompt.txt"), "utf8");
const target = path.join(root, "packages", "reader", "src", "quiz-llm-prompt.js");
const output = `// Generated from docs/quiz-llm-prompt.txt by scripts/generate-quiz-llm-prompt.mjs.\n// Do not edit this file directly; edit the prompt document and regenerate.\nexport const QUIZ_LLM_PROMPT = ${JSON.stringify(source)};\n`;
fs.writeFileSync(target, output, "utf8");
console.log(target);
