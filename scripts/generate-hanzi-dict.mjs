// Generates the compact single-character glossary used by the selection
// pinyin/definition popup. Source: chinese-xinhua (MIT), data/word.json.
//
//   node scripts/generate-hanzi-dict.mjs [--source <word.json>]
//
// Without --source the script downloads the dataset into node_modules/.cache.
// The generated module is committed; rerun only when the source updates.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const output = path.join(repoRoot, "packages/reader/src/hanzi-dict-data.js");
const cacheDir = path.join(repoRoot, "node_modules/.cache/chinese-xinhua");
const cacheFile = path.join(cacheDir, "word.json");

const SOURCES = [
  "https://ghproxy.net/https://raw.githubusercontent.com/pwxcoo/chinese-xinhua/master/data/word.json",
  "https://gh-proxy.com/https://raw.githubusercontent.com/pwxcoo/chinese-xinhua/master/data/word.json",
  "https://raw.githubusercontent.com/pwxcoo/chinese-xinhua/master/data/word.json",
];

const MAX_GLOSS = 64;
const CJK = /^[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]$/u;
const PINYIN_CHARS = "a-züǖǘǚǜāáǎàēéěèīíǐìōóǒòūúǔùńňǹ·";

function sourcePath() {
  const index = process.argv.indexOf("--source");
  if (index >= 0 && process.argv[index + 1]) return process.argv[index + 1];
  return "";
}

async function loadSource() {
  const explicit = sourcePath();
  if (explicit) return JSON.parse(fs.readFileSync(explicit, "utf8"));
  if (fs.existsSync(cacheFile)) return JSON.parse(fs.readFileSync(cacheFile, "utf8"));
  fs.mkdirSync(cacheDir, { recursive: true });
  let lastError = null;
  for (const url of SOURCES) {
    try {
      console.log("downloading", url);
      const response = await fetch(url);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const text = await response.text();
      fs.writeFileSync(cacheFile, text);
      return JSON.parse(text);
    } catch (error) {
      lastError = error;
      console.warn("  failed:", error.message);
    }
  }
  throw lastError || new Error("could not download the dataset");
}

const SENSE_MARKER = /[⒉-⒛]|(?:^|\s)[2-9][.、]/u;
const POS_ONLY = /^(?:〈[^〉]*〉|[（(][^）)]*[）)]|本义|同本义|引申|形声|会意|象形|指事)\s*$/u;

function cleanSense(value) {
  return String(value || "")
    .replace(/〈[^〉]*〉/g, " ")
    .replace(/^[⒈1][.、．)）]?\s*/u, "")
    .replace(/\s+/g, " ")
    .trim();
}

// The modern dictionary section starts with the character followed by its
// reading (e.g. "好hǎo\n⒈勇敢…"); take that section's first sense.
function senseAfterMarker(body) {
  const nextSense = body.search(SENSE_MARKER);
  const head = nextSense > 0 ? body.slice(0, nextSense) : body;
  return cleanSense(head.split(/\n+/).map((line) => line.trim()).find(Boolean));
}

// Some entries (e.g. 餮, 彧) end with a bare reading marker and keep the actual
// definition in an earlier block; fall back to the first real sentence.
function firstMeaningfulBlock(body) {
  const blocks = body.split(/\n+/).map((line) => line.trim()).filter(Boolean);
  for (const block of blocks) {
    const cleaned = cleanSense(block).replace(/^[（(][^）)]*[）)]/, "").trim();
    if (cleaned.length < 2 || POS_ONLY.test(cleaned)) continue;
    if (/^(?:[⒈-⒛]|\d+[.、])/u.test(cleaned)) continue;
    return cleaned;
  }
  return "";
}

export function compactGloss(word, explanation) {
  const raw = String(explanation || "");
  const marker = new RegExp(`(?:^|\\s)${word}[${PINYIN_CHARS}]+`, "u");
  const match = marker.exec(raw);
  let gloss = "";
  if (match) gloss = senseAfterMarker(raw.slice(match.index + match[0].length));
  if (!gloss) {
    const body = raw.replace(new RegExp(`^\\s*${word}[${PINYIN_CHARS}]*\\s*`, "u"), "");
    gloss = firstMeaningfulBlock(body);
  }
  if (!gloss) return "";
  const firstStop = gloss.indexOf("。");
  if (firstStop >= 8) gloss = gloss.slice(0, firstStop + 1);
  if (gloss.length > MAX_GLOSS) {
    const cut = gloss.slice(0, MAX_GLOSS);
    const stop = Math.max(cut.lastIndexOf("。"), cut.lastIndexOf("；"), cut.lastIndexOf("，"), cut.lastIndexOf(";"));
    gloss = stop > MAX_GLOSS * 0.4 ? cut.slice(0, stop + 1) : `${cut.replace(/[，、；;]$/u, "")}…`;
  }
  return gloss;
}

function escapeValue(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

async function main() {
  const data = await loadSource();
  const entries = [];
  for (const entry of data) {
    const word = String(entry?.word || "").trim();
    if (!CJK.test(word)) continue;
    const gloss = compactGloss(word, entry?.explanation);
    if (!gloss) continue;
    entries.push([word, gloss]);
  }
  entries.sort((a, b) => a[0].localeCompare(b[0], "zh"));
  const lines = entries.map(([word, gloss]) => `  "${escapeValue(word)}": "${escapeValue(gloss)}",`);
  const module = `// Generated by scripts/generate-hanzi-dict.mjs — do not edit.
// Source: chinese-xinhua data/word.json (MIT). Single-character glosses only.
export const HANZI_GLOSSES = Object.freeze({
${lines.join("\n")}
});
`;
  fs.writeFileSync(output, module);
  console.log(`wrote ${entries.length} glosses -> ${path.relative(repoRoot, output)} (${Math.round(module.length / 1024)} KB)`);
}

const isDirect = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirect) await main();
