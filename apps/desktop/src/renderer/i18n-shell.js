export function shellText(plugin, source, ...args) {
  const language = String(plugin?.settings?.language || "zh").toLowerCase();
  let out = language.startsWith("zh") ? String(source) : (EN[source] ?? String(source));
  if (args.length) {
    out = out.replace(/\{(\d+)\}/g, (match, index) => args[Number(index)] ?? match);
  }
  return out;
}
